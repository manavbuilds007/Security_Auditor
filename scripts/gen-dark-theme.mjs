import fs from 'node:fs';
const theme = fs.readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const val = (name) => {
  const m = theme.match(new RegExp(`--color-${name}:\\s*([^;]+);`));
  if (!m) throw new Error('missing ' + name);
  return m[1].trim();
};
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const invert = (s) => shades[shades.length - 1 - shades.indexOf(s)];

// Brand navy neutral scale (matches the intro: #050b18 family). Text tones were checked for >= 4.5:1 on the panel colour.
const NAVY = {
  white: '#0b1426', // panels / cards
  50: '#060d1c', // page background, inset blocks
  100: '#12203a', // hover surfaces
  200: '#1d2d4a', // borders
  300: '#2b3d60', // stronger borders
  400: '#7d8ca8', // placeholder / de-emphasised text (>= 4.5:1)
  500: '#97a6bf', // secondary text
  600: '#b6c2d6',
  700: '#cbd5e4',
  800: '#e2e8f0',
  900: '#f1f5f9',
  950: '#f8fafc',
};
const accents = [
  'rose',
  'red',
  'orange',
  'amber',
  'lime',
  'emerald',
  'teal',
  'cyan',
  'sky',
  'blue',
  'indigo',
  'violet',
  'purple',
  'fuchsia',
  'pink',
];

let out = `/* Generated by scripts/gen-dark-theme.mjs from tailwindcss/theme.css plus a hand-tuned navy neutral scale. Do not edit by hand. */\n.dark {\n  color-scheme: dark;\n  --color-white: ${NAVY.white};\n`;
for (const s of shades) out += `  --color-slate-${s}: ${NAVY[s]};\n`;
for (const c of accents) for (const s of shades) out += `  --color-${c}-${s}: ${val(c + '-' + invert(s))};\n`;
out += '}\n';
fs.writeFileSync('src/dark-theme.css', out);
console.log(out.split('\n').length, 'lines');
